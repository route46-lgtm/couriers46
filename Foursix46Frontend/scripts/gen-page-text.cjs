/* ─────────────────────────────────────────────────────────────────────────────
   scripts/gen-page-text.cjs
   Builds src/content/pageText.generated.ts — the list of editable text fields
   the admin "Page text" tab shows for each page. It reads the pages' own
   <Txt k="…">{"…"}</Txt> and txt("…", "…") calls, so the admin always matches
   the code. Runs as part of `npm run build`; run by hand after editing a page:
     node scripts/gen-page-text.cjs
───────────────────────────────────────────────────────────────────────────── */

const ts = require("typescript");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src/content/pageText.generated.ts");

// Order here = order in the admin.
const PAGES = [
  { id: "about", label: "About page", path: "/about", file: "src/pages/AboutPage.tsx" },
  { id: "forBusinesses", label: "For Businesses page", path: "/for-businesses", file: "src/pages/ForBusinessesPage.tsx" },
  { id: "becomeDriver", label: "Become a Driver page", path: "/become-driver", file: "src/pages/BecomeDriverPage.tsx" },
  { id: "contact", label: "Contact page", path: "/contact", file: "src/pages/ContactPage.tsx" },
  { id: "accredited", label: "Accredited & Trusted page", path: "/accredited-trusted", file: "src/pages/AccreditedTrustedPage.tsx" },
  { id: "pay", label: "Secure Payment page", path: "/pay", file: "src/pages/PayPage.tsx" },
  { id: "privacy", label: "Privacy Policy", path: "/privacy", file: "src/pages/PrivacyPolicyPage.tsx" },
  { id: "terms", label: "Terms & Conditions", path: "/terms", file: "src/pages/TermsPage.tsx" },
  { id: "cookies", label: "Cookies Policy", path: "/cookies", file: "src/pages/CookiesPage.tsx" },
  { id: "refund", label: "Refund Policy", path: "/refund-policy", file: "src/pages/RefundPolicyPage.tsx" },
];

const KIND_BY_TAG = {
  h1: "Heading", h2: "Heading", h3: "Sub-heading", h4: "Sub-heading", h5: "Sub-heading", h6: "Sub-heading",
  CardTitle: "Heading", DialogTitle: "Heading",
  p: "Paragraph", CardDescription: "Paragraph", blockquote: "Quote",
  li: "List item", td: "Table cell", th: "Table heading",
  button: "Button", Button: "Button", a: "Link", Link: "Link", NavLink: "Link",
  label: "Form label", Label: "Form label", FormLabel: "Form label", FormDescription: "Form help text",
  SelectItem: "Dropdown option", Badge: "Badge", strong: "Bold text", b: "Bold text", em: "Italic text",
};
const SECTION_TAGS = new Set(["h1", "h2", "h3", "CardTitle"]);
const pretty = (s) => s.charAt(0).toUpperCase() + s.slice(1).replace(/([A-Z])/g, " $1").toLowerCase();

function tagOf(el) {
  return (ts.isJsxElement(el) ? el.openingElement : el).tagName.getText();
}

function scan(page) {
  const file = path.join(ROOT, page.file);
  const src = fs.readFileSync(file, "utf8");
  const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const fields = [];
  const keys = new Set();
  let section = "Top of page";

  const add = (key, def, kind) => {
    if (keys.has(key)) return;
    keys.add(key);
    fields.push({ key, label: kind, default: def, multiline: def.length > 90, section });
  };

  const visit = (node) => {
    // <Txt k="…">{"…"}</Txt>
    if (ts.isJsxElement(node) && tagOf(node) === "Txt") {
      const kAttr = node.openingElement.attributes.properties.find(
        (p) => ts.isJsxAttribute(p) && p.name.getText() === "k",
      );
      const child = node.children.find((c) => ts.isJsxExpression(c) && c.expression);
      if (kAttr && kAttr.initializer && ts.isStringLiteral(kAttr.initializer) && child && ts.isStringLiteral(child.expression)) {
        const parentTag = ts.isJsxElement(node.parent) ? tagOf(node.parent) : "";
        const def = child.expression.text;
        if (SECTION_TAGS.has(parentTag)) section = def.trim();
        add(kAttr.initializer.text, def, KIND_BY_TAG[parentTag] || "Text");
      }
      return;
    }
    // txt("…", "…")
    if (ts.isCallExpression(node) && node.expression.getText() === "txt" && node.arguments.length === 2 &&
        ts.isStringLiteral(node.arguments[0]) && ts.isStringLiteral(node.arguments[1])) {
      const p = node.parent;
      let kind = "Text";
      if (ts.isPropertyAssignment(p)) kind = pretty(p.name.getText().replace(/["']/g, ""));
      else if (ts.isJsxExpression(p) && ts.isJsxAttribute(p.parent)) kind = pretty(p.parent.name.getText());
      else if (ts.isArrayLiteralExpression(p)) kind = "List item";
      add(node.arguments[0].text, node.arguments[1].text, kind);
      return;
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  return { id: `page-${page.id}`, label: `${page.label} (${page.path})`, path: page.path, fields };
}

const groups = PAGES.map(scan);
const total = groups.reduce((n, g) => n + g.fields.length, 0);
const body =
  `/* AUTO-GENERATED by scripts/gen-page-text.cjs — do not edit by hand.\n` +
  `   Editable text fields per page for Admin → Site Content → Page text. */\n\n` +
  `import type { PageTextGroup } from "./siteContent";\n\n` +
  `export const PAGE_TEXT_GROUPS: PageTextGroup[] = ${JSON.stringify(groups, null, 2)};\n`;
fs.writeFileSync(OUT, body);
console.log(`[page-text] ${total} editable fields across ${groups.length} pages → src/content/pageText.generated.ts`);
